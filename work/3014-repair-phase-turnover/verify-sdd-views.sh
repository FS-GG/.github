#!/usr/bin/env bash
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
out="${1:-$root/work/3014-repair-phase-turnover/test-results/sdd-views.junit.xml}"
sdd="${FSGG_SDD_BIN:-/tmp/fsgg-sdd-140.VDJZfU/fsgg-sdd}"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

cd "$root"
"$sdd" analyze --work 3014-repair-phase-turnover --json >"$tmp"
jq -e '.toolVersion == "1.4.0" and (.outcome == "succeeded" or .outcome == "noChange") and .analysis.readiness == "implementationReady" and .analysis.blockingCount == 0 and .analysis.staleSourceCount == 0' "$tmp" >/dev/null
jq -e '.workId == "3014-repair-phase-turnover" and .modelVersion == "1.2.0" and ((.sources | length) >= 6) and ((.diagnostics | length) == 0)' readiness/3014-repair-phase-turnover/work-model.json >/dev/null

mkdir -p "$(dirname "$out")"
cat >"$out" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<testsuite name="repair-phase turnover SDD source views" tests="2" failures="0" errors="0" skipped="0">
  <testcase classname="sdd" name="analysis is implementationReady with zero blockers or stale sources" />
  <testcase classname="sdd" name="work model is regenerated by vetted FS.GG.SDD 1.4.0 from the complete source package" />
</testsuite>
XML

printf 'REPAIR-PHASE-TURNOVER-SDD-VIEWS-GREEN: 2/2\n'
